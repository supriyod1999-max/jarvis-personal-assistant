// The application mounts this boundary even while release-held. No HTTPS
// transport is installed here by default; bootstrap may supply a reviewed factory.
import { AsyncLocalStorage } from 'node:async_hooks';
import { join } from 'node:path';
import { evergreenPrivacy } from './evergreen-privacy.mjs';
import { createEvergreenMemberSessions } from './evergreen-member-surface.mjs';
import { CAPABILITIES, integrationError as fail } from './evergreen-contract.mjs';

const off = () => ({ processWithAI: false, retainChat: false, agreedAt: null });
export function createEvergreenHost({ directory, profileId, serverId, lock, principalAllowed, generate, redactChat, registryFactory }) {
  const context = new AsyncLocalStorage(), tickets = new WeakMap();
  // Server ID is durable and generated by JARVIS, not a profile label or email.
  // Mapping this principal to an Evergreen UID still needs reviewed release data.
  const subject = `jarvis-workspace:${serverId}:${profileId}`;
  let closed = false;
  function authenticate(ticket) {
    const origin = tickets.get(ticket);
    if (closed || !origin || !principalAllowed(origin.req, origin.viaPhone)) return null;
    const session = lock.session(origin.req);
    if (!session || session.profileId !== profileId) return null;
    return { ...session, subject };
  }
  // A factory is a trusted server dependency for isolated acceptance and later
  // coordinated release. Neither environment nor request fields supply one.
  let registry = null;
  try { registry = registryFactory?.({ directory, profileId, subject, authenticate }) || null; }
  catch (e) { if (e.code !== 'release_held') throw e; } // Hold this integration, not ordinary JARVIS.
  const sessions = registry ? createEvergreenMemberSessions({ registry, authenticate,
    generate: (identity, prompt) => {
      if (identity.profileId !== profileId || identity.subject !== subject) throw fail('denied', 403);
      return generate(prompt);
    }, redactChat: identity => {
      if (identity.profileId !== profileId || identity.subject !== subject) throw fail('denied', 403);
      return redactChat();
    },
  }) : null;
  // Setup preferences are workspace-local, never imported as consent into a
  // future verified connection. Held requests still use the off() runtime policy.
  const setupPrivacy = !sessions ? evergreenPrivacy(join(directory, 'evergreen-setup')) : null;
  const held = () => ({ state: 'release-held', problem: 'release_held', mode: 'household', liveEnabled: false, pairing: null, connection: null, records: 0, requests: [], capabilities: CAPABILITIES.map(c => ({ ...c, rolloutEnabled: false })), privacy: setupPrivacy?.get() || off(), localPreferencesOnly: !!setupPrivacy });
  const current = () => { const c = context.getStore(); if (!c || closed) throw fail('context_changed', 409); return c; };
  async function surface() {
    if (!sessions) throw fail('release_held', 503);
    const c = current();
    c.surface ||= await sessions.forRequest(c.ticket);
    return c.surface;
  }
  const api = {
    configured: !!registry,
    withRequest(req, viaPhone, run) {
      // Call only after the HTTP host/Origin/Tailscale and PIN boundary.
      const ticket = Object.freeze({});
      tickets.set(ticket, { req: { method: req.method, headers: { ...req.headers }, socket: { remoteAddress: req.socket.remoteAddress } }, viaPhone });
      return context.run({ ticket, privacy: off(), surface: null }, run);
    },
    async status() {
      if (!sessions) return held();
      const c = current();
      try { const state = await (await surface()).status(); c.privacy = state.privacy; return state; }
      catch (e) { if (e.code !== 'release_held') throw e; c.problem = e; return held(); }
    },
    async records(input) { return (await surface()).records(input); },
    async settings(operation, input) {
      if (setupPrivacy && ['privacy', 'redact-chat'].includes(operation)) {
        if (!authenticate(current().ticket)) throw fail('denied', 403);
        if (!input || typeof input !== 'object' || Array.isArray(input) || input.confirm !== true) throw fail('invalid');
        if (operation === 'redact-chat') {
          if (Object.keys(input).some(k => k !== 'confirm')) throw fail('invalid');
          return redactChat();
        }
        if (Object.keys(input).some(k => !['processWithAI', 'retainChat', 'confirm'].includes(k)) || typeof input.processWithAI !== 'boolean' || typeof input.retainChat !== 'boolean') throw fail('invalid');
        if (!input.retainChat) await redactChat();
        return setupPrivacy.set(input);
      }
      if (operation === 'end-session') {
        if (!input || typeof input !== 'object' || Array.isArray(input) || Object.keys(input).length) throw fail('invalid');
        if (sessions) await sessions.endSession(current().ticket);
        return { ended: true };
      }
      const result = await (await surface()).settings(operation, input);
      if (['privacy', 'redact-chat'].includes(operation)) current().privacy = result;
      return result;
    },
    async prepareChat(input, previousTurn) {
      if (input && ['memberUid', 'householdId', 'profileId', 'connectionHandle', 'subject'].some(k => k in input)) throw fail('invalid');
      const c = current();
      c.forceEvergreen = (previousTurn?.provider === 'evergreen-companion' || previousTurn?.privacyTag === 'evergreen') && /^(?:actually|no\b|yes\b|change\b|make\b|instead\b|cancel\b)/i.test(input?.message || '');
      if (sessions) { try { await api.status(); } catch (e) { c.problem = e; } }
    },
    retainChat() {
      const c = context.getStore();
      return !!c && c.privacy.retainChat === true && !!authenticate(c.ticket);
    },
    handles(request) {
      return /\bevergreen\b/i.test(request.message) || context.getStore()?.surface?.handles(request) === true || context.getStore()?.forceEvergreen === true;
    },
    run(request, onText) {
      if (!api.handles(request)) return null;
      let active, cancelled = false;
      const ready = surface().then(async s => {
        if (current().problem) throw current().problem;
        if (cancelled) throw fail('context_changed', 409);
        active = await s.talk(request, onText);
        if (!active) throw fail('context_changed', 409); // Never fall through to general inference.
        if (cancelled) await active.cancel();
        return active;
      });
      return { done: ready.then(r => r.done), cancel: async () => { cancelled = true; try { await (await ready).cancel(); } catch { /* Original error belongs to done. */ } } };
    },
    async interruptReview(turn) { if (!closed && sessions && context.getStore()) return (await surface()).interruptReview({ conversationId: turn.conversationId, turnId: turn.id }); },
    async endRequestSession(req, viaPhone) {
      if (!sessions || !lock.session(req)) return;
      return api.withRequest(req, viaPhone, async () => { await sessions.endSession(current().ticket); });
    },
    async close() { closed = true; await sessions?.close(); await registry?.close(); },
  };
  return api;
}
